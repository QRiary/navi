/**
 * “Layer keys bring their layer to the top” (firmware.layerKeysOnTop): the C state logic for keymap.c.
 *
 * QMK shows the highest layer that is on, so a key for a lower layer seems to do nothing while a higher one is on.
 * Here the layer turned on last wins: navi_wanted holds the layers the keys asked for, and what QMK shows
 * (layer_state) is navi_wanted without the layers above the newest one.
 *
 * A hidden layer's bit is 0 in layer_state, so QMK turning it off (layer_off) changes nothing and never reaches
 * layer_state_set_user, and toggling it (layer_invert) looks like turning it on. navi_layer_keys() sees those keys
 * in process_record before QMK acts on them (same conditions as QMK's action.c) and fixes navi_wanted first;
 * it never swallows a key. A one-shot layer that ends while hidden is caught in the layer callback itself:
 * QMK clears the one-shot state before its layer_off().
 */

/** Static state and helpers, emitted above process_record_* (needs MAX_LAYER and the QK_* getters from QMK). */
export function layerOnTopState(): string[] {
  return [
    '// ── Layer keys bring their layer to the top: the layer turned on last wins ──',
    '// navi_wanted: the layers the keys turned on (hidden ones too); navi_order: the same layers, oldest first.',
    '// What QMK shows is navi_wanted without the layers above the newest one.',
    'static layer_state_t navi_wanted    = 0;',
    'static layer_state_t navi_ignore_on = 0; // hidden layers QMK is about to invert: that turns them off, not on',
    'static layer_state_t navi_key_off   = 0; // the layer the key being handled turns off (or inverts)',
    '#ifndef NO_ACTION_ONESHOT',
    'static layer_state_t navi_oneshot   = 0; // the layer a one-shot key turned on',
    '#endif',
    'static uint8_t navi_order[MAX_LAYER];',
    'static uint8_t navi_count = 0;',
    '',
    'static void navi_forget(uint8_t layer) {',
    '    uint8_t kept = 0;',
    '    for (uint8_t i = 0; i < navi_count; i++) {',
    '        if (navi_order[i] != layer) navi_order[kept++] = navi_order[i];',
    '    }',
    '    navi_count = kept;',
    '    navi_wanted &= ~((layer_state_t)1 << layer);',
    '}',
    '',
    'static void navi_remember(uint8_t layer) {',
    '    navi_forget(layer);',
    '    navi_order[navi_count++] = layer;',
    '    navi_wanted |= (layer_state_t)1 << layer;',
    '}',
    '',
    '// navi_wanted without the layers above the newest one.',
    'static layer_state_t navi_visible(void) {',
    '    if (navi_count == 0) return 0;',
    '    layer_state_t upto = ((layer_state_t)2 << navi_order[navi_count - 1]) - 1;',
    '    return navi_wanted & upto;',
    '}',
    '',
    '// The layers turned on, hidden ones included (for your own LEDs or checks).',
    'layer_state_t navi_layers_on(void) {',
    '    return navi_wanted;',
    '}',
    '',
    '// Turns a layer off from your own C, also while it is hidden (layer_off() alone does not reach a hidden layer).',
    'void navi_layer_off(uint8_t layer) {',
    '    if (layer >= MAX_LAYER) return;',
    '    if (layer_state & ((layer_state_t)1 << layer)) {',
    '        layer_off(layer);',
    '    } else {',
    '        navi_forget(layer); // hidden: the visible layers stay as they are',
    '    }',
    '}',
    '',
    '// A layer key about to turn off (or invert) a hidden layer: QMK will not see the change, so NAVI applies it now.',
    'static void navi_layer_keys(uint16_t keycode, keyrecord_t *record) {',
    '    navi_ignore_on = 0;',
    '    navi_key_off   = 0;',
    '    bool    pressed = record->event.pressed;',
    '    bool    invert  = false;',
    '    uint8_t layer   = 0;',
    '    switch (keycode) {',
    '        case QK_MOMENTARY ... QK_MOMENTARY_MAX:',
    '            if (pressed) return;',
    '            layer = QK_MOMENTARY_GET_LAYER(keycode);',
    '            break;',
    '        case QK_LAYER_MOD ... QK_LAYER_MOD_MAX:',
    '            if (pressed) return;',
    '            layer = QK_LAYER_MOD_GET_LAYER(keycode);',
    '            break;',
    '#ifndef NO_ACTION_TAPPING',
    '        case QK_LAYER_TAP ... QK_LAYER_TAP_MAX:',
    '            if (pressed || record->tap.count > 0) return; // a tap sends its key, the layer was never on',
    '            layer = QK_LAYER_TAP_GET_LAYER(keycode);',
    '            break;',
    '        case QK_LAYER_TAP_TOGGLE ... QK_LAYER_TAP_TOGGLE_MAX:',
    '            // QMK inverts the layer on press while tap.count < TAPPING_TOGGLE, on release while <= TAPPING_TOGGLE.',
    '            if (pressed ? record->tap.count >= TAPPING_TOGGLE : record->tap.count > TAPPING_TOGGLE) return;',
    '            layer  = QK_LAYER_TAP_TOGGLE_GET_LAYER(keycode);',
    '            invert = true;',
    '            break;',
    '#elif defined(NO_ACTION_TAPPING_TAP_TOGGLE_MO)',
    '        case QK_LAYER_TAP_TOGGLE ... QK_LAYER_TAP_TOGGLE_MAX: // works like MO without tapping',
    '            if (pressed) return;',
    '            layer = QK_LAYER_TAP_TOGGLE_GET_LAYER(keycode);',
    '            break;',
    '#else',
    '        case QK_LAYER_TAP_TOGGLE ... QK_LAYER_TAP_TOGGLE_MAX: // works like TG without tapping',
    '            if (pressed) return;',
    '            layer  = QK_LAYER_TAP_TOGGLE_GET_LAYER(keycode);',
    '            invert = true;',
    '            break;',
    '#endif',
    '        case QK_TOGGLE_LAYER ... QK_TOGGLE_LAYER_MAX:',
    '            if (pressed) return; // TG acts on release',
    '            layer  = QK_TOGGLE_LAYER_GET_LAYER(keycode);',
    '            invert = true;',
    '            break;',
    '#ifndef NO_ACTION_ONESHOT',
    '        case QK_ONE_SHOT_LAYER ... QK_ONE_SHOT_LAYER_MAX:',
    '            // With one-shot keys turned off (OS_OFF) OSL works like MO; otherwise the layer callback sees it end.',
    '            if (pressed || keymap_config.oneshot_enable) return;',
    '            layer = QK_ONE_SHOT_LAYER_GET_LAYER(keycode);',
    '            break;',
    '#endif',
    '        case QK_TO ... QK_TO_MAX:',
    '            // TO(n) leaves only layer n on: the hidden layers go too.',
    '            if (pressed) {',
    '                layer_state_t hidden = navi_wanted & ~layer_state;',
    '                for (uint8_t l = 0; l < MAX_LAYER; l++) {',
    '                    if (hidden & ((layer_state_t)1 << l)) navi_forget(l);',
    '                }',
    '            }',
    '            return;',
    '        default:',
    '            return;',
    '    }',
    '    if (layer >= MAX_LAYER) return;',
    '    layer_state_t bit = (layer_state_t)1 << layer;',
    '    navi_key_off      = bit;',
    '    if (!(navi_wanted & bit) || (layer_state & bit)) return; // not hidden: QMK\'s change reaches layer_state_set',
    '    navi_forget(layer); // hidden layers are above the newest one, so what QMK shows stays the same',
    '    if (invert) navi_ignore_on |= bit;',
    '}',
    '',
  ];
}

/** The layer callback: layer_state_set_user (pure QMK) or layer_state_set_navi (own pipeline). */
export function layerOnTopCallback(name: string, languageLayer = false): string[] {
  // Languages: the current language's layer stays on, at the bottom of navi_order, so it never covers a held layer.
  const keep = languageLayer
    ? [
        '    // The current language’s layer stays on, under the others (Languages).',
        '    uint8_t keep = navi_language_layer();',
        '    // The default layer turned on by a key (TO) is under everything anyway: it must not hide the language’s layer.',
        '    uint8_t base = get_highest_layer(default_layer_state);',
        '    if (keep < MAX_LAYER && keep != base && (navi_wanted & ((layer_state_t)1 << base))) navi_forget(base);',
        '    if (keep < MAX_LAYER && !(navi_wanted & ((layer_state_t)1 << keep))) {',
        '        for (uint8_t i = navi_count; i > 0; i--) navi_order[i] = navi_order[i - 1];',
        '        navi_order[0] = keep;',
        '        navi_count++;',
        '        navi_wanted |= (layer_state_t)1 << keep;',
        '    }',
      ]
    : [];
  return [
    `layer_state_t ${name}(layer_state_t state) {`,
    '    layer_state_t turned_on  = state & ~layer_state;',
    '    layer_state_t turned_off = layer_state & ~state;',
    '    layer_state_t on         = turned_on & ~navi_ignore_on;',
    '    navi_ignore_on &= ~turned_on;',
    '    // State 0 is layer_clear(), unless it is the last shown layer going off (a layer key or a one-shot ending):',
    '    // then the hidden layers stay on.',
    '    bool clear = state == 0 && turned_off != navi_key_off;',
    '#ifndef NO_ACTION_ONESHOT',
    '    if (clear && turned_off == navi_oneshot && !is_oneshot_layer_active()) clear = false;',
    '#endif',
    '    if (clear) {',
    '        navi_count  = 0;',
    '        navi_wanted = 0;',
    '    }',
    '    for (uint8_t l = 0; l < MAX_LAYER; l++) {',
    '        if (turned_off & ((layer_state_t)1 << l)) navi_forget(l);',
    '    }',
    '    for (uint8_t l = 0; l < MAX_LAYER; l++) {',
    '        if (on & ((layer_state_t)1 << l)) navi_remember(l);',
    '    }',
    '#ifndef NO_ACTION_ONESHOT',
    '    // QMK clears the one-shot state before turning its layer off, so a hidden one-shot layer that ended is seen here.',
    '    if (is_oneshot_layer_active()) {',
    '        layer_state_t osl = (layer_state_t)1 << get_oneshot_layer();',
    '        if (on & osl) navi_oneshot = osl;',
    '    } else if (navi_oneshot) {',
    '        for (uint8_t l = 0; l < MAX_LAYER; l++) {',
    '            if (navi_oneshot & ((layer_state_t)1 << l)) navi_forget(l);',
    '        }',
    '        navi_oneshot = 0;',
    '    }',
    '#endif',
    ...keep,
    '    return navi_visible();',
    '}',
    '',
  ];
}

/**
 * Own pipeline with the setting off: the same functions, plain QMK behavior, so the user's calls always compile.
 * `callback`: also the layer callback (not when languages write their own).
 */
export function layerOnTopStubs(callback = true): string[] {
  return [
    ...(callback ? ['layer_state_t layer_state_set_navi(layer_state_t state) {', '    return state;', '}'] : []),
    'layer_state_t navi_layers_on(void) {',
    '    return layer_state;',
    '}',
    'void navi_layer_off(uint8_t layer) {',
    '    layer_off(layer);',
    '}',
  ];
}
